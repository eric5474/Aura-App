#!/usr/bin/env node
'use strict';
/* Builds the Android app's web files into www/.
   - index.html gets a full document shell (the same one server.js adds)
   - remote.js = JioSaavn client + app glue + live-mode adapter, so the app needs no server */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const pub = path.join(root, 'public');
const www = path.join(root, 'www');

fs.rmSync(www, { recursive: true, force: true });
fs.mkdirSync(www, { recursive: true });

const shell = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<meta name="theme-color" content="#111514">
<link rel="icon" href="logo-64.png" type="image/png">
<style>:root{color-scheme:light;padding-top:env(safe-area-inset-top);padding-bottom:env(safe-area-inset-bottom)}body{margin:0;font:14px/1.4 system-ui,sans-serif;-webkit-tap-highlight-color:transparent}img{max-width:100%}[hidden]{display:none!important}</style>
</head>
<body>
`;
fs.writeFileSync(path.join(www, 'index.html'), shell + fs.readFileSync(path.join(pub, 'index.html'), 'utf8') + '\n</body>\n</html>\n');

const client = fs.readFileSync(path.join(root, 'jiosaavn.js'), 'utf8');
const charts = fs.readFileSync(path.join(root, 'charts.js'), 'utf8');
const sources = fs.readFileSync(path.join(root, 'sources.js'), 'utf8');
// optional: a Jamendo client id baked into the app (from the AURA_JAMENDO_CLIENT_ID build secret)
const baked = {};
for (const k of ['AURA_JAMENDO_CLIENT_ID', 'AURA_YOUTUBE_API_KEY']) if (process.env[k]) baked[k] = process.env[k];
const env = Object.keys(baked).length ? 'globalThis.AURA_ENV = ' + JSON.stringify(baked) + ';\n' : '';
const bundle = [
  '/* AURA Android bundle, generated by scripts/build-app.js. Edit the source files, not this one. */',
  env + '(function () { var module; /* jiosaavn.js */\n' + client + '\n})();',
  '(function () { var module; /* charts.js */\n' + charts + '\n})();',
  '(function () { var module; /* sources.js */\n' + sources + '\n})();',
  fs.readFileSync(path.join(root, 'app', 'native.js'), 'utf8'),
  fs.readFileSync(path.join(pub, 'remote.js'), 'utf8'),
].join('\n\n');
fs.writeFileSync(path.join(www, 'remote.js'), bundle);

for (const f of fs.readdirSync(pub)) {
  if (/\.(png|jpg|svg|webmanifest)$/.test(f)) fs.copyFileSync(path.join(pub, f), path.join(www, f));
}
console.log('Built www/ for the Android app:', fs.readdirSync(www).join(', '));
